"""Pydantic models for validation results and reports.

These models define the structure of validation outputs,
ensuring type safety and serialization consistency.
"""

from datetime import datetime
from enum import Enum
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field


class ValidationSeverity(str, Enum):
    """Severity levels for validation issues."""
    ERROR = "error"
    WARNING = "warning"
    INFO = "info"


class ValidationIssue(BaseModel):
    """A single validation issue found in the data.

    Attributes:
        field: Column or field where the issue was found.
        row_index: Row index in the DataFrame (None for dataset-level issues).
        rule: Name of the validation rule that flagged this.
        severity: Issue severity level.
        message: Human-readable description of the issue.
        value: The problematic value (serialized as string).
    """
    field: str
    row_index: Optional[int] = None
    rule: str
    severity: ValidationSeverity = ValidationSeverity.ERROR
    message: str
    value: Optional[str] = None


class ValidationReport(BaseModel):
    """Complete validation report for a single dataset.

    Generated by the validation engine after checking all rules.
    Contains both summary statistics and individual issues.
    """
    dataset_name: str
    timestamp: datetime = Field(default_factory=datetime.utcnow)
    total_records: int = 0
    valid_records: int = 0
    rejected_records: int = 0
    issues: List[ValidationIssue] = Field(default_factory=list)
    issues_by_severity: Dict[str, int] = Field(default_factory=dict)
    columns_checked: List[str] = Field(default_factory=list)
    missing_columns: List[str] = Field(default_factory=list)
    extra_columns: List[str] = Field(default_factory=list)
    duplicate_count: int = 0
    is_valid: bool = True

    def add_issue(self, issue: ValidationIssue) -> None:
        """Add a validation issue and update counters."""
        self.issues.append(issue)
        severity_key = issue.severity.value
        self.issues_by_severity[severity_key] = (
            self.issues_by_severity.get(severity_key, 0) + 1
        )
        if issue.severity == ValidationSeverity.ERROR:
            self.is_valid = False

    def summary(self) -> Dict[str, Any]:
        """Return a concise summary dictionary for logging/reporting."""
        return {
            "dataset": self.dataset_name,
            "total_records": self.total_records,
            "valid_records": self.valid_records,
            "rejected_records": self.rejected_records,
            "is_valid": self.is_valid,
            "error_count": self.issues_by_severity.get("error", 0),
            "warning_count": self.issues_by_severity.get("warning", 0),
            "missing_columns": self.missing_columns,
            "duplicate_count": self.duplicate_count,
        }

